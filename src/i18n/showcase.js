export function detectLanguage(preferences) {
  for (const preference of preferences) {
    const [language, ...variants] = preference.toLowerCase().split("-");
    if (language === "zh") {
      if (variants.includes("hant")) return "zh-Hant";
      if (variants.includes("hans")) return "zh-Hans";
      return variants.some(code => ["tw", "hk", "mo"].includes(code)) ? "zh-Hant" : "zh-Hans";
    }
    if (Object.hasOwn(messages, language)) return language;
  }
  return "pl";
}
